// Collapse repeated records that point to the same concrete LinkedIn job URL.
// Placeholder text such as "Not captured" is intentionally left untouched.
const statusRank = {
  'Submitted': 6,
  'In progress': 5,
  'Needs input': 4,
  'Ready': 3,
  'Ready for application': 3,
  'Halted': 2,
  'Discovered': 1
};
const preferredByLinkedInUrl = new Map();
for (let i = 0; i < data.length; i += 1) {
  const row = data[i];
  const url = row['LinkedIn URL'];
  if (!/^https:\/\/www\.linkedin\.com\/jobs\/view\/\d+\/$/.test(url || '')) continue;
  const current = preferredByLinkedInUrl.get(url);
  if (current == null) {
    preferredByLinkedInUrl.set(url, i);
    continue;
  }
  const currentRow = data[current];
  const rowDate = row['Date discovered'] || '';
  const currentDate = currentRow['Date discovered'] || '';
  const rowRank = statusRank[row['Application status']] || 0;
  const currentRank = statusRank[currentRow['Application status']] || 0;
  if (rowDate > currentDate || (rowDate === currentDate && rowRank > currentRank) || (rowDate === currentDate && rowRank === currentRank)) {
    preferredByLinkedInUrl.set(url, i);
  }
}
